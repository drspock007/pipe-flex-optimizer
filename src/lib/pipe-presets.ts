/** Get wall thickness options for a given NPS, with a "Custom" entry appended. */
export function getWallThicknessOptions(nps: string): WallThicknessOption[] {
  const options = WALL_THICKNESS_BY_NPS[nps] || [];
  return [...options, { schedule: "Custom", wt_mm: null }];
}

/** Try to find the NPS that matches a given OD (mm). Returns nps string or "CUSTOM". */
export function findNpsByOd(od_mm: number): string {
  const match = PIPE_SIZES.find(p => p.od_mm !== null && Math.abs(p.od_mm - od_mm) < 0.05);
  return match ? match.nps : "CUSTOM";
}

/** Try to find the schedule that matches a given WT (mm) for a given NPS. Returns schedule string or "Custom". */
export function findScheduleByWt(nps: string, wt_mm: number): string {
  const options = WALL_THICKNESS_BY_NPS[nps];
  if (!options) return "Custom";
  const match = options.find(o => Math.abs(o.wt_mm - wt_mm) < 0.05);
  return match ? match.schedule : "Custom";
}
